-- Reusable logical stage: recognized order lines exclude cancelled, refunded,
-- and pending orders before any downstream aggregation occurs.
WITH completed_lines AS (
    SELECT
        o.order_id,
        o.customer_id,
        o.order_date,
        oi.product_id,
        oi.quantity,
        oi.unit_price,
        p.unit_cost,
        p.category_id,
        oi.quantity * oi.unit_price AS line_revenue,
        oi.quantity * (oi.unit_price - p.unit_cost) AS line_profit
    FROM orders AS o
    JOIN order_items AS oi USING (order_id)
    JOIN products AS p USING (product_id)
    WHERE o.status = 'completed'
)
SELECT
    c.customer_name,
    COUNT(DISTINCT cl.order_id) AS completed_orders,
    COALESCE(SUM(cl.line_revenue), 0)::NUMERIC(14, 2) AS recognized_revenue,
    COALESCE(SUM(cl.line_profit), 0)::NUMERIC(14, 2) AS gross_profit
FROM customers AS c
LEFT JOIN completed_lines AS cl USING (customer_id)
GROUP BY c.customer_id, c.customer_name
ORDER BY recognized_revenue DESC, c.customer_name;

-- Chained CTEs separate filtering, aggregation, and analytical ranking.
WITH
completed_lines AS (
    SELECT
        oi.product_id,
        oi.quantity,
        oi.unit_price,
        p.unit_cost,
        p.category_id
    FROM orders AS o
    JOIN order_items AS oi USING (order_id)
    JOIN products AS p USING (product_id)
    WHERE o.status = 'completed'
),
category_totals AS (
    SELECT
        c.category_id,
        c.category_name,
        SUM(cl.quantity) AS units_sold,
        SUM(cl.quantity * cl.unit_price) AS revenue,
        SUM(cl.quantity * (cl.unit_price - cl.unit_cost)) AS gross_profit
    FROM completed_lines AS cl
    JOIN categories AS c USING (category_id)
    GROUP BY c.category_id, c.category_name
),
ranked_categories AS (
    SELECT
        *,
        DENSE_RANK() OVER (ORDER BY gross_profit DESC) AS profit_rank,
        SUM(gross_profit) OVER () AS total_profit
    FROM category_totals
)
SELECT
    category_name,
    units_sold,
    ROUND(revenue, 2) AS revenue,
    ROUND(gross_profit, 2) AS gross_profit,
    profit_rank,
    ROUND(100 * gross_profit / NULLIF(total_profit, 0), 2) AS profit_share_pct
FROM ranked_categories
ORDER BY profit_rank, category_name;

-- A window function compares each monthly aggregate with the previous month
-- present in the result. Missing months are not silently treated as zero.
WITH monthly_revenue AS (
    SELECT
        date_trunc('month', o.order_date)::DATE AS month_start,
        SUM(oi.quantity * oi.unit_price) AS revenue
    FROM orders AS o
    JOIN order_items AS oi USING (order_id)
    WHERE o.status = 'completed'
    GROUP BY date_trunc('month', o.order_date)::DATE
),
month_comparison AS (
    SELECT
        month_start,
        revenue,
        LAG(revenue) OVER (ORDER BY month_start) AS previous_revenue
    FROM monthly_revenue
)
SELECT
    month_start,
    ROUND(revenue, 2) AS revenue,
    ROUND(previous_revenue, 2) AS previous_revenue,
    ROUND(revenue - previous_revenue, 2) AS absolute_change,
    ROUND(
        100 * (revenue - previous_revenue) / NULLIF(previous_revenue, 0),
        2
    ) AS percentage_change
FROM month_comparison
ORDER BY month_start;

-- Cohort analysis: cohort_month is each customer's first completed purchase.
-- Activity is counted distinctly at customer-month grain to avoid order inflation.
WITH
first_purchase AS (
    SELECT
        customer_id,
        date_trunc('month', MIN(order_date))::DATE AS cohort_month
    FROM orders
    WHERE status = 'completed'
    GROUP BY customer_id
),
customer_activity AS (
    SELECT DISTINCT
        customer_id,
        date_trunc('month', order_date)::DATE AS activity_month
    FROM orders
    WHERE status = 'completed'
),
cohort_sizes AS (
    SELECT cohort_month, COUNT(*) AS cohort_size
    FROM first_purchase
    GROUP BY cohort_month
),
cohort_activity AS (
    SELECT
        fp.cohort_month,
        ca.activity_month,
        (
            EXTRACT(YEAR FROM age(ca.activity_month, fp.cohort_month)) * 12
            + EXTRACT(MONTH FROM age(ca.activity_month, fp.cohort_month))
        )::INTEGER AS month_offset,
        COUNT(DISTINCT ca.customer_id) AS active_customers
    FROM first_purchase AS fp
    JOIN customer_activity AS ca USING (customer_id)
    GROUP BY fp.cohort_month, ca.activity_month
)
SELECT
    a.cohort_month,
    a.activity_month,
    a.month_offset,
    a.active_customers,
    s.cohort_size,
    ROUND(100.0 * a.active_customers / NULLIF(s.cohort_size, 0), 2)
        AS retention_percentage
FROM cohort_activity AS a
JOIN cohort_sizes AS s USING (cohort_month)
WHERE a.month_offset >= 0
ORDER BY a.cohort_month, a.month_offset;

-- Recursive CTE: traverse a category tree and preserve a readable path.
-- The path check prevents repeated category IDs from recurring in a cycle.
WITH RECURSIVE category_tree AS (
    SELECT
        category_id,
        category_name,
        parent_category_id,
        0 AS depth,
        ARRAY[category_id] AS visited_ids,
        category_name::TEXT AS path
    FROM categories
    WHERE parent_category_id IS NULL

    UNION ALL

    SELECT
        child.category_id,
        child.category_name,
        child.parent_category_id,
        parent.depth + 1,
        parent.visited_ids || child.category_id,
        parent.path || ' > ' || child.category_name
    FROM categories AS child
    JOIN category_tree AS parent
      ON child.parent_category_id = parent.category_id
    WHERE NOT child.category_id = ANY(parent.visited_ids)
      AND parent.depth < 50
)
SELECT category_id, category_name, parent_category_id, depth, path
FROM category_tree
ORDER BY path;

-- Aggregate status counts separately from recognized financial value.
-- This makes excluded states visible rather than silently discarding them.
WITH order_line_totals AS (
    SELECT
        o.order_id,
        o.status,
        SUM(oi.quantity * oi.unit_price) AS order_value
    FROM orders AS o
    JOIN order_items AS oi USING (order_id)
    GROUP BY o.order_id, o.status
),
status_summary AS (
    SELECT
        status,
        COUNT(*) AS orders,
        SUM(order_value) AS order_value
    FROM order_line_totals
    GROUP BY status
)
SELECT
    status,
    orders,
    ROUND(order_value, 2) AS order_value,
    ROUND(100.0 * orders / NULLIF(SUM(orders) OVER (), 0), 2)
        AS order_count_share_pct
FROM status_summary
ORDER BY orders DESC, status;

