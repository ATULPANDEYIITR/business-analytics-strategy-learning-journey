-- Transactional workflow: change the order state and insert an audit-like
-- payment record together. If either operation fails, both are rolled back.
SAVEPOINT settlement_demo;

DO $$
BEGIN
    BEGIN
        INSERT INTO payments (
            order_id, amount, payment_status, paid_at
        )
        VALUES (106, 22800.00, 'settled', CURRENT_TIMESTAMP);

        UPDATE orders
        SET status = 'shipped',
            shipped_at = CURRENT_TIMESTAMP
        WHERE order_id = 106
          AND status = 'paid';

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Order 106 was not in the paid state';
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            RAISE NOTICE 'Settlement transaction rejected: %', SQLERRM;
            RAISE;
    END;
END;
$$;

-- Roll back the demonstration transaction to preserve the original sample.
ROLLBACK TO SAVEPOINT settlement_demo;
RELEASE SAVEPOINT settlement_demo;

COMMIT;
