-- Advanced joins: aggregate each independent one-to-many relationship before
-- joining it to the order. Otherwise item rows multiply payment rows.
WITH item_totals AS (
    SELECT
        order_id,
        SUM(quantity * unit_price * (1 - discount_rate)) AS net_total
    FROM order_items
    GROUP BY order_id
),
payment_totals AS (
    SELECT
        order_id,
        SUM(amount) FILTER (WHERE payment_status = 'settled') AS settled_total
    FROM payments
    GROUP BY order_id
),
ticket_totals AS (
    SELECT
        order_id,
        COUNT(*) AS ticket_count,
        COUNT(*) FILTER (WHERE resolved_at IS NULL) AS open_ticket_count
    FROM support_tickets
    WHERE order_id IS NOT NULL
    GROUP BY order_id
)
SELECT
    o.order_id,
    c.customer_name,
    o.status,
    COALESCE(i.net_total, 0) AS net_total,
    COALESCE(p.settled_total, 0) AS settled_total,
    COALESCE(t.ticket_count, 0) AS ticket_count,
    COALESCE(t.open_ticket_count, 0) AS open_ticket_count
FROM orders AS o
JOIN customers AS c ON c.customer_id = o.customer_id
LEFT JOIN item_totals AS i ON i.order_id = o.order_id
LEFT JOIN payment_totals AS p ON p.order_id = o.order_id
LEFT JOIN ticket_totals AS t ON t.order_id = o.order_id
ORDER BY o.order_id;

-- Outer join semantics: the delivered-order predicate belongs in ON if
-- customers without delivered orders must remain in the result.
SELECT
    c.customer_id,
    c.customer_name,
    COUNT(o.order_id) AS delivered_order_count
FROM customers AS c
LEFT JOIN orders AS o
  ON o.customer_id = c.customer_id
 AND o.status = 'delivered'
GROUP BY c.customer_id, c.customer_name
ORDER BY delivered_order_count, c.customer_id;

-- NOT EXISTS is a robust anti-join, even if the subquery's key can be NULL.
SELECT c.customer_id, c.customer_name
FROM customers AS c
WHERE NOT EXISTS (
    SELECT 1
    FROM support_tickets AS t
    WHERE t.customer_id = c.customer_id
)
ORDER BY c.customer_id;

-- LATERAL allows a correlated top-one lookup per customer. The index created
-- below supports filtering and descending date order.
SELECT
    c.customer_id,
    c.customer_name,
    latest.order_id,
    latest.order_date,
    latest.status
FROM customers AS c
LEFT JOIN LATERAL (
    SELECT o.order_id, o.order_date, o.status
    FROM orders AS o
    WHERE o.customer_id = c.customer_id
    ORDER BY o.order_date DESC, o.order_id DESC
    LIMIT 1
) AS latest ON TRUE
ORDER BY c.customer_id;

-- Window functions: ranking and distribution.
WITH customer_revenue AS (
    SELECT
        c.customer_id,
        c.customer_name,
        c.region,
        COALESCE(
            SUM(oi.quantity * oi.unit_price * (1 - oi.discount_rate))
                FILTER (WHERE o.status <> 'cancelled'),
            0
        ) AS revenue
    FROM customers AS c
    LEFT JOIN orders AS o ON o.customer_id = c.customer_id
    LEFT JOIN order_items AS oi ON oi.order_id = o.order_id
    GROUP BY c.customer_id, c.customer_name, c.region
)
SELECT
    customer_id,
    customer_name,
    region,
    revenue,
    RANK() OVER (
        PARTITION BY region ORDER BY revenue DESC
    ) AS regional_rank,
    DENSE_RANK() OVER (
        ORDER BY revenue DESC
    ) AS overall_dense_rank,
    ROW_NUMBER() OVER (
        PARTITION BY region ORDER BY revenue DESC, customer_id
    ) AS deterministic_row_number,
    NTILE(4) OVER (ORDER BY revenue DESC) AS revenue_quartile
FROM customer_revenue
ORDER BY region, regional_rank, customer_id;

-- Running totals and trailing averages use explicit ROWS frames. Here each
-- input row represents one calendar date after daily aggregation.
WITH daily_revenue AS (
    SELECT
        o.order_date,
        SUM(oi.quantity * oi.unit_price * (1 - oi.discount_rate)) AS revenue
    FROM orders AS o
    JOIN order_items AS oi ON oi.order_id = o.order_id
    WHERE o.status = 'delivered'
    GROUP BY o.order_date
)
SELECT
    order_date,
    revenue,
    SUM(revenue) OVER (
        ORDER BY order_date
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS running_revenue,
    AVG(revenue) OVER (
        ORDER BY order_date
        ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
    ) AS trailing_three_observation_average,
    LAG(revenue) OVER (ORDER BY order_date) AS previous_observation_revenue,
    revenue - LAG(revenue) OVER (ORDER BY order_date) AS change_from_previous
FROM daily_revenue
ORDER BY order_date;

-- Window functions do not collapse rows. Use a subquery to filter by a
-- computed window value because PostgreSQL cannot use a window expression
-- directly in WHERE.
WITH ranked_orders AS (
    SELECT
        o.*,
        ROW_NUMBER() OVER (
            PARTITION BY customer_id
            ORDER BY order_date DESC, order_id DESC
        ) AS newest_first
    FROM orders AS o
)
SELECT order_id, customer_id, order_date, status
FROM ranked_orders
WHERE newest_first = 1
ORDER BY customer_id;

-- Query optimization: index definitions should follow actual filter, join,
-- and ordering patterns. A multicolumn B-tree is most useful when leading
-- columns align with the query's restrictions.
CREATE INDEX idx_orders_customer_date
    ON orders (customer_id, order_date DESC, order_id DESC);

CREATE INDEX idx_orders_status_date
    ON orders (status, order_date);

CREATE INDEX idx_order_items_product
    ON order_items (product_id, order_id);

CREATE INDEX idx_payments_order_status
    ON payments (order_id, payment_status);

CREATE INDEX idx_support_tickets_customer_open
    ON support_tickets (customer_id, opened_at DESC)
    WHERE resolved_at IS NULL;

