-- A materialized view persists expensive aggregates between refreshes.
-- It is useful for read-heavy reporting, but its contents become stale until
-- refreshed. PostgreSQL can concurrently refresh only under suitable unique
-- index and populated-view conditions.
CREATE MATERIALIZED VIEW monthly_regional_revenue AS
SELECT
    DATE_TRUNC('month', o.order_date)::DATE AS month_start,
    c.region,
    SUM(oi.quantity * oi.unit_price * (1 - oi.discount_rate)) AS revenue
FROM orders AS o
JOIN customers AS c ON c.customer_id = o.customer_id
JOIN order_items AS oi ON oi.order_id = o.order_id
WHERE o.status = 'delivered'
GROUP BY DATE_TRUNC('month', o.order_date)::DATE, c.region;

CREATE UNIQUE INDEX idx_monthly_region
    ON monthly_regional_revenue (month_start, region);

SELECT month_start, region, revenue
FROM monthly_regional_revenue
ORDER BY month_start, region;

REFRESH MATERIALIZED VIEW monthly_regional_revenue;

