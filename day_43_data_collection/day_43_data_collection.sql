    purpose TEXT NOT NULL,
    lawful_basis TEXT NOT NULL,
    schema_version TEXT NOT NULL DEFAULT '1.0',
    payload JSONB NOT NULL,
    outcome collection_outcome NOT NULL DEFAULT 'accepted',
    rejection_reason TEXT,
    CONSTRAINT unique_source_external_record
        UNIQUE (source_id, external_record_id),
    CONSTRAINT external_record_id_not_blank
        CHECK (btrim(external_record_id) <> ''),
    CONSTRAINT record_purpose_not_blank
        CHECK (btrim(purpose) <> ''),
    CONSTRAINT record_lawful_basis_not_blank
        CHECK (btrim(lawful_basis) <> ''),
    CONSTRAINT collection_time_valid
        CHECK (observed_at <= collected_at),
    CONSTRAINT payload_is_object
        CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT rejection_reason_consistent
        CHECK (
            (outcome = 'rejected' AND rejection_reason IS NOT NULL)
