/*
Data Collection Governance: Internal, External, Transactional, and Behavioral

PostgreSQL 15+.
This script creates a self-contained demonstration schema, loads realistic
records, enforces source-specific data quality and collection controls,
and produces analytical results.

The four categories have different operational meanings:
- Internal: data generated by systems operated by the organization.
- External: data supplied by a third party or outside source.
- Transactional: records of business transactions and their outcomes.
- Behavioral: events describing observed user interactions.

Run in a disposable database. The schema reset is intentional.
*/

