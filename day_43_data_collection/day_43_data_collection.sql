-- Database views keep category-specific metrics separate.
CREATE VIEW v_collection_profile AS
SELECT
    category,
    count(*) AS accepted_record_count,
    min(observed_at) AS first_observation,
    max(observed_at) AS latest_observation
FROM collection_records
WHERE outcome = 'accepted'
GROUP BY category;

CREATE VIEW v_paid_revenue_by_currency AS
SELECT
    currency,
    count(*) AS paid_order_count,
    sum(amount) AS paid_revenue,
    avg(amount) AS average_paid_order_value
FROM sales_orders
WHERE status = 'paid'
GROUP BY currency;

CREATE VIEW v_behavioral_funnel AS
SELECT
    event_type,
    count(*) AS event_count,
    count(DISTINCT visitor_reference) AS distinct_visitors
FROM behavioral_events
GROUP BY event_type;

CREATE VIEW v_inventory_availability AS
SELECT
    warehouse_code,
    sku,
    available_units,
    reserved_units,
    available_units - reserved_units AS unreserved_units
FROM inventory_snapshots;

-- Data-quality query: records that lack an appropriate typed subtype.
SELECT
    record.record_id,
    record.category,
    record.external_record_id,
    'Missing category-specific record' AS quality_issue
FROM collection_records AS record
WHERE
    (record.category = 'internal' AND NOT EXISTS (
        SELECT 1 FROM inventory_snapshots AS inventory
        WHERE inventory.record_id = record.record_id
    ))
    OR
    (record.category = 'external' AND NOT EXISTS (
        SELECT 1 FROM supplier_quotes AS quote
        WHERE quote.record_id = record.record_id
    ))
    OR
    (record.category = 'transactional' AND NOT EXISTS (
        SELECT 1 FROM sales_orders AS sales_order
        WHERE sales_order.record_id = record.record_id
    ))
    OR
    (record.category = 'behavioral' AND NOT EXISTS (
        SELECT 1 FROM behavioral_events AS event
        WHERE event.record_id = record.record_id
    ));

