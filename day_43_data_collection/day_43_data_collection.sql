-- Source-to-record category consistency is enforced by this trigger.
CREATE FUNCTION enforce_source_category()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    registered_category data_category;
    registered_purpose TEXT;
    registered_basis TEXT;
    registered_enabled BOOLEAN;
    registered_consent_required BOOLEAN;
    latest_permission BOOLEAN;
BEGIN
    SELECT
        category,
        purpose,
        lawful_basis,
        enabled,
        consent_required
    INTO
        registered_category,
        registered_purpose,
        registered_basis,
        registered_enabled,
        registered_consent_required
    FROM collection_sources
    WHERE source_id = NEW.source_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Collection source does not exist';
    END IF;

    IF NOT registered_enabled THEN
        RAISE EXCEPTION 'Collection source is disabled';
    END IF;

    IF NEW.category <> registered_category THEN
        RAISE EXCEPTION
            'Record category does not match registered source category';
    END IF;

    IF NEW.purpose <> registered_purpose
       OR NEW.lawful_basis <> registered_basis THEN
        RAISE EXCEPTION
            'Record purpose or lawful basis conflicts with source policy';
    END IF;

    IF registered_consent_required THEN
        IF NEW.subject_id IS NULL THEN
            RAISE EXCEPTION 'Subject is required for this source';
        END IF;

        SELECT allowed
        INTO latest_permission
        FROM collection_permissions
        WHERE subject_id = NEW.subject_id
          AND purpose = NEW.purpose
        ORDER BY recorded_at DESC, permission_id DESC
        LIMIT 1;

        IF latest_permission IS DISTINCT FROM TRUE THEN
            RAISE EXCEPTION
                'Latest permission does not authorize this purpose';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_enforce_source_category
BEFORE INSERT OR UPDATE ON collection_records
FOR EACH ROW
EXECUTE FUNCTION enforce_source_category();

-- Enforce consistency between the generic record and its typed subtype.
CREATE FUNCTION enforce_subtype_category()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    parent_category data_category;
BEGIN
    SELECT category
    INTO parent_category
    FROM collection_records
    WHERE record_id = NEW.record_id;

    IF parent_category IS DISTINCT FROM TG_ARGV[0]::data_category THEN
        RAISE EXCEPTION
            'Subtype category does not match parent collection record';
    END IF;

    RETURN NEW;
END;
$$;

