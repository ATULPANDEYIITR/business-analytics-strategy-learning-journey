def weighted_average_margin(products: List[Product]) -> float:
    """
    Calculate the business-level contribution margin ratio.

    Important:
        Do not calculate an average by simply averaging percentages.

    Incorrect:
        (50% + 10%) / 2 = 30%

    Correct:
        Total Contribution Margin / Total Revenue

    Revenue volume must influence the weighting.
    """
    total_product_revenue = sum(
        product.revenue
        for product in products
    )

    total_product_contribution = sum(
        product.contribution_margin
        for product in products
    )

    if total_product_revenue == 0:
        return 0.0

    return (
        total_product_contribution
        / total_product_revenue
    )


