def cost_volume_profit_table(
    fixed_cost: float,
    selling_price: float,
    variable_cost_per_unit: float,
    unit_levels: List[int],
) -> List[Dict[str, float]]:
    """
    Create a Cost-Volume-Profit table.

    Cost-Volume-Profit analysis studies how changes in:
        - Sales volume
        - Selling price
        - Variable cost
        - Fixed cost

    affect profit.
    """
    results = []

    for units in unit_levels:
        revenue = selling_price * units
        variable_cost = variable_cost_per_unit * units
        total_cost = fixed_cost + variable_cost
        profit = revenue - total_cost

        results.append(
            {
                "units": units,
                "revenue": revenue,
                "variable_cost": variable_cost,
                "fixed_cost": fixed_cost,
                "total_cost": total_cost,
                "profit": profit,
            }
        )

    return results


