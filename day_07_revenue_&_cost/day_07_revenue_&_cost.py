"""
Revenue:
    Money earned from selling goods or services.

Revenue Stream:
    A distinct source through which a business earns revenue.

Examples:
    - Product sales
    - Subscription fees
    - Advertising
    - Consulting
    - Licensing
    - Transaction commissions

Fixed Cost:
    A cost that generally does not change with short-term production or sales
    volume within a relevant operating range.

Examples:
    - Office rent
    - Salaried administration
    - Insurance
    - Software subscriptions
    - Depreciation

Variable Cost:
    A cost that changes with production or sales volume.

Examples:
    - Raw materials
    - Product packaging
    - Sales commissions
    - Payment processing fees
    - Shipping per order

Total Cost:
    Fixed Costs + Variable Costs

Margin:
    A measure of how much money remains after certain costs are deducted.

Contribution Margin:
    Revenue - Variable Costs

Gross Margin:
    Revenue - Cost of Goods Sold

Operating Margin:
    Operating Profit / Revenue

Net Margin:
    Net Profit / Revenue
"""


