def calculate_revenue(price_per_unit: float, units_sold: int) -> float:
    """
    Calculate revenue from a single product.

    Formula:
        Revenue = Price per Unit × Units Sold

    Raises:
        ValueError if price or units are negative.
    """
    if price_per_unit < 0:
        raise ValueError("Price per unit cannot be negative.")

    if units_sold < 0:
        raise ValueError("Units sold cannot be negative.")

    return price_per_unit * units_sold


