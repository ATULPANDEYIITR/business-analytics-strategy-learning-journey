@dataclass
class UnitEconomics:
    """
    Represents the economics of one unit, customer, order, or transaction.

    Unit economics is useful for answering questions such as:

    - Does each sale create value?
    - Does each customer contribute toward fixed costs?
    - Is growth profitable at the unit level?
    """

    selling_price: float
    variable_cost_per_unit: float

    def __post_init__(self) -> None:
        if self.selling_price < 0:
            raise ValueError("Selling price cannot be negative.")

        if self.variable_cost_per_unit < 0:
            raise ValueError("Variable cost cannot be negative.")

    @property
    def contribution_margin(self) -> float:
        return self.selling_price - self.variable_cost_per_unit

    @property
    def contribution_margin_ratio(self) -> float:
        if self.selling_price == 0:
            return 0.0

        return self.contribution_margin / self.selling_price

    @property
    def is_positive(self) -> bool:
        return self.contribution_margin > 0


