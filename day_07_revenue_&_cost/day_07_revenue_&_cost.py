def margin_percentage(
    selling_price: float,
    cost: float,
) -> float:
    """
    Margin Percentage:
        (Selling Price - Cost) / Selling Price
    """
    if selling_price == 0:
        return 0.0

    return (
        selling_price - cost
    ) / selling_price


def markup_percentage(
    selling_price: float,
    cost: float,
) -> Optional[float]:
    """
    Markup Percentage:
        (Selling Price - Cost) / Cost

    Cost equal to zero makes markup mathematically undefined.
    """
    if cost == 0:
        return None

    return (
        selling_price - cost
    ) / cost


