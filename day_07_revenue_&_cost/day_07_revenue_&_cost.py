def contribution_margin_per_unit(
    selling_price: float,
    variable_cost_per_unit: float,
) -> float:
    """
    Calculate contribution margin per unit.

    Formula:
        Contribution Margin per Unit
        = Selling Price per Unit - Variable Cost per Unit

    Contribution margin contributes toward:
        1. Covering fixed costs
        2. Generating profit after fixed costs are covered
    """
    return selling_price - variable_cost_per_unit


def contribution_margin_ratio(
    selling_price: float,
    variable_cost_per_unit: float,
) -> float:
    """
    Calculate contribution margin ratio.

    Formula:
        Contribution Margin Ratio
        = Contribution Margin / Revenue

    For a single unit:
        (Price - Variable Cost) / Price
    """
    if selling_price == 0:
        return 0.0

    return (
        selling_price - variable_cost_per_unit
    ) / selling_price


selling_price = 500.0
variable_cost = 180.0

cm_per_unit = contribution_margin_per_unit(
    selling_price,
    variable_cost,
)

cm_ratio = contribution_margin_ratio(
    selling_price,
    variable_cost,
)

