def minimum_price_for_target_margin(
    variable_cost: float,
    target_margin_ratio: float,
) -> Optional[float]:
    """
    Calculate minimum price required for a target contribution margin ratio.

    Formula:
        Target Margin = (Price - Variable Cost) / Price

    Rearranging:
        Price = Variable Cost / (1 - Target Margin)

    Example:
        Variable Cost = 600
        Target Margin = 40%

        Price = 600 / (1 - 0.40)
        Price = 1,000
    """
    if variable_cost < 0:
        raise ValueError("Variable cost cannot be negative.")

    if not 0 <= target_margin_ratio < 1:
        return None

    return variable_cost / (
        1 - target_margin_ratio
    )


