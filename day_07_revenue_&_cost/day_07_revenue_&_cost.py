def operating_leverage(
    contribution_margin_value: float,
    operating_profit_value: float,
) -> Optional[float]:
    """
    Simplified Degree of Operating Leverage.

    DOL = Contribution Margin / Operating Profit

    A high operating leverage business has relatively high fixed costs.

    Consequences:
        - Revenue growth can increase profits rapidly.
        - Revenue decline can reduce profits rapidly.

    The metric becomes unstable near zero operating profit and is not meaningful
    when operating profit is exactly zero.
    """
    if operating_profit_value == 0:
        return None

    return (
        contribution_margin_value
        / operating_profit_value
    )


