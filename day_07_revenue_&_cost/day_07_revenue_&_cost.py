def break_even_units(
    fixed_cost: float,
    selling_price: float,
    variable_cost_per_unit: float,
) -> Optional[float]:
    """
    Calculate break-even sales volume.

    Formula:
        Break-even Units
        = Fixed Cost / Contribution Margin per Unit

    If contribution margin is zero or negative, the business cannot cover
    fixed costs through increased sales under the current economics.
    """
    contribution = selling_price - variable_cost_per_unit

    if contribution <= 0:
        return None

    return fixed_cost / contribution


def break_even_revenue(
    fixed_cost: float,
    contribution_margin_ratio_value: float,
) -> Optional[float]:
    """
    Calculate break-even revenue.

    Formula:
        Break-even Revenue
        = Fixed Cost / Contribution Margin Ratio
    """
    if contribution_margin_ratio_value <= 0:
        return None

    return fixed_cost / contribution_margin_ratio_value


