def maximum_profit_with_capacity(
    price: float,
    variable_cost_per_unit: float,
    fixed_cost: float,
    market_demand: int,
    production_capacity: int,
) -> Dict[str, float]:
    """
    Analyze profit when production capacity limits sales.

    Actual sales cannot exceed the lower of:
        - Market demand
        - Production capacity
    """
    if market_demand < 0:
        raise ValueError(
            "Market demand cannot be negative."
        )

    if production_capacity < 0:
        raise ValueError(
            "Production capacity cannot be negative."
        )

    units_sold = min(
        market_demand,
        production_capacity,
    )

    revenue = price * units_sold

    variable_cost = (
        variable_cost_per_unit
        * units_sold
    )

    profit = (
        revenue
        - variable_cost
        - fixed_cost
    )

    return {
        "units_sold": units_sold,
        "revenue": revenue,
        "variable_cost": variable_cost,
        "profit": profit,
    }


