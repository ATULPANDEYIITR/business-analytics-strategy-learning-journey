@dataclass
class Scenario:
    """
    Represents a financial scenario.

    Scenario analysis helps evaluate uncertainty by changing assumptions.
    """

    name: str
    price: float
    variable_cost_per_unit: float
    units_sold: int
    fixed_cost: float

    def evaluate(self) -> Dict[str, float]:
        revenue = self.price * self.units_sold

        total_variable_cost = (
            self.variable_cost_per_unit
            * self.units_sold
        )

        contribution_margin_value = (
            revenue
            - total_variable_cost
        )

        profit = (
            contribution_margin_value
            - self.fixed_cost
        )

        profit_margin_value = (
            profit / revenue
            if revenue != 0
            else 0.0
        )

        return {
            "revenue": revenue,
            "variable_cost": total_variable_cost,
            "contribution_margin": contribution_margin_value,
            "fixed_cost": self.fixed_cost,
            "profit": profit,
            "profit_margin": profit_margin_value,
        }


