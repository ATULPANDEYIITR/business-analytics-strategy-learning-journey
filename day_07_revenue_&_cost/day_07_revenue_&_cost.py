def gross_profit(revenue: float, cost_of_goods_sold: float) -> float:
    """
    Gross Profit = Revenue - Cost of Goods Sold.

    Cost of Goods Sold, commonly abbreviated as COGS, generally includes
    direct costs associated with producing or acquiring goods sold.
    """
    return revenue - cost_of_goods_sold


def gross_margin(revenue: float, cost_of_goods_sold: float) -> float:
    """
    Gross Margin = Gross Profit / Revenue.

    The result is expressed as a decimal.
    """
    if revenue == 0:
        return 0.0

    return gross_profit(revenue, cost_of_goods_sold) / revenue


