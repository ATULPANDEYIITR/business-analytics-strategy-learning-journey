def price_sensitivity_analysis(
    base_price: float,
    variable_cost: float,
    units: int,
    fixed_cost: float,
    percentage_changes: List[float],
) -> List[Dict[str, float]]:
    """
    Evaluate how changes in price affect revenue and profit.

    A percentage change of:
        -0.10 means a 10% decrease
         0.10 means a 10% increase
    """
    results = []

    for change in percentage_changes:
        new_price = base_price * (
            1 + change
        )

        revenue = new_price * units

        total_variable_cost = (
            variable_cost * units
        )

        profit = (
            revenue
            - total_variable_cost
            - fixed_cost
        )

        results.append(
            {
                "price_change": change,
                "price": new_price,
                "revenue": revenue,
                "profit": profit,
            }
        )

    return results


