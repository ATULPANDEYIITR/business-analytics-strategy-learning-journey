@dataclass
class Product:
    """
    Represents a product or service with pricing and cost characteristics.
    """

    name: str
    price: float
    variable_cost_per_unit: float
    units_sold: int

    def __post_init__(self) -> None:
        if self.price < 0:
            raise ValueError("Price cannot be negative.")

        if self.variable_cost_per_unit < 0:
            raise ValueError("Variable cost cannot be negative.")

        if self.units_sold < 0:
            raise ValueError("Units sold cannot be negative.")

    @property
    def revenue(self) -> float:
        return self.price * self.units_sold

    @property
    def total_variable_cost(self) -> float:
        return self.variable_cost_per_unit * self.units_sold

    @property
    def contribution_margin(self) -> float:
        return self.revenue - self.total_variable_cost

    @property
    def contribution_margin_ratio(self) -> float:
        if self.revenue == 0:
            return 0.0

        return self.contribution_margin / self.revenue


@dataclass
class Business:
    """
    Represents a simplified multi-product business.

    The model separates:
        - Product-level variable economics
        - Business-level fixed costs

    This separation is important because fixed costs must eventually be covered
    by the combined contribution margins of products.
    """

    name: str
    products: List[Product] = field(default_factory=list)
    fixed_costs: List[FixedCost] = field(default_factory=list)

    @property
    def total_revenue(self) -> float:
        return sum(product.revenue for product in self.products)

    @property
    def total_variable_cost(self) -> float:
        return sum(
            product.total_variable_cost
            for product in self.products
        )

    @property
    def total_contribution_margin(self) -> float:
        return (
            self.total_revenue
            - self.total_variable_cost
        )

    @property
    def total_fixed_cost(self) -> float:
        return sum(cost.amount for cost in self.fixed_costs)

    @property
    def operating_profit(self) -> float:
        return (
            self.total_contribution_margin
            - self.total_fixed_cost
        )

    @property
    def operating_margin(self) -> float:
        if self.total_revenue == 0:
            return 0.0

        return (
            self.operating_profit
            / self.total_revenue
        )


