def units_required_for_target_profit(
    fixed_cost: float,
    target_profit: float,
    selling_price: float,
    variable_cost_per_unit: float,
) -> Optional[float]:
    """
    Calculate units required to achieve a target profit.

    Formula:
        Required Units
        = (Fixed Costs + Target Profit)
          / Contribution Margin per Unit
    """
    contribution = (
        selling_price
        - variable_cost_per_unit
    )

    if contribution <= 0:
        return None

    return (
        fixed_cost + target_profit
    ) / contribution


