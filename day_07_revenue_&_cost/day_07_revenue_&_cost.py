def calculate_step_fixed_cost(
    units: int,
    capacity_per_facility: int,
    facility_cost: float,
) -> float:
    """
    Demonstrate step-fixed costs.

    Some costs remain fixed only within a capacity range.

    Example:
        One warehouse handles up to 1,000 units.
        Demand above 1,000 units requires another warehouse.

    This creates a step pattern rather than a perfectly flat fixed cost.
    """
    if units <= 0:
        return 0.0

    facilities_required = math.ceil(
        units / capacity_per_facility
    )

    return (
        facilities_required
        * facility_cost
    )


