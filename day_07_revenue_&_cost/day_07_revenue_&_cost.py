def margin_of_safety(
    actual_units: int,
    break_even_units_value: float,
) -> float:
    """
    Margin of Safety measures how far current sales exceed break-even sales.

    Formula:
        (Actual Sales - Break-even Sales) / Actual Sales
    """
    if actual_units <= 0:
        return 0.0

    return (
        actual_units
        - break_even_units_value
    ) / actual_units


