def calculate_total_cost(
    fixed_cost: float,
    variable_cost_per_unit: float,
    units: int,
) -> float:
    """
    Calculate total cost.

    Formula:
        Total Cost = Fixed Cost + Total Variable Cost

        Total Variable Cost = Variable Cost per Unit × Units
    """
    if fixed_cost < 0:
        raise ValueError("Fixed cost cannot be negative.")

    if variable_cost_per_unit < 0:
        raise ValueError("Variable cost per unit cannot be negative.")

    if units < 0:
        raise ValueError("Units cannot be negative.")

    return fixed_cost + variable_cost_per_unit * units


