@dataclass
class CustomerEconomics:
    """
    Simplified customer economics model.

    Revenue can be compared against the variable cost of serving the customer.

    For subscription businesses, a customer may generate recurring revenue over
    multiple periods.
    """

    monthly_revenue: float
    monthly_variable_cost: float
    expected_months: int
    acquisition_cost: float

    @property
    def lifetime_revenue(self) -> float:
        return (
            self.monthly_revenue
            * self.expected_months
        )

    @property
    def lifetime_variable_cost(self) -> float:
        return (
            self.monthly_variable_cost
            * self.expected_months
        )

    @property
    def lifetime_contribution_before_acquisition(
        self,
    ) -> float:
        return (
            self.lifetime_revenue
            - self.lifetime_variable_cost
        )

    @property
    def customer_profitability(self) -> float:
        return (
            self.lifetime_contribution_before_acquisition
            - self.acquisition_cost
        )


