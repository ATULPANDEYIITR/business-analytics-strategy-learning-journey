new_customers = 500

cac = customer_acquisition_cost(
    sales_marketing_cost,
    new_customers
)

print(f"Sales and marketing cost: ${sales_marketing_cost:,.2f}")
print(f"New customers: {new_customers}")
print(f"CAC: ${cac:,.2f}")

print("""
Customer Acquisition Cost, or CAC:

    CAC
    =
    Sales and Marketing Cost
    /
    Number of New Customers

If a company spends $100,000 and acquires 500 customers:

    CAC = $200

CAC must be interpreted alongside customer quality and lifetime value.

A low CAC is not automatically good.

If the customers generate almost no economic value, a low acquisition
cost does not make the model attractive.

Similarly, a high CAC can be justified when customers produce
substantial long-term contribution.
""")


