def simple_ltv(
    average_revenue_per_period,
    gross_margin,
    retention_rate
):
    if retention_rate >= 1:
        return float("inf")
    expected_lifetime = 1 / (1 - retention_rate)
    return (
        average_revenue_per_period
        * gross_margin
        * expected_lifetime
    )


monthly_revenue = 100
gross_margin = 0.80
monthly_retention = 0.95

ltv = simple_ltv(
    monthly_revenue,
    gross_margin,
    monthly_retention
)

print(f"Monthly revenue: ${monthly_revenue}")
print(f"Gross margin: {gross_margin:.0%}")
print(f"Monthly retention: {monthly_retention:.0%}")
print(f"Simple LTV estimate: ${ltv:,.2f}")

print("""
Customer Lifetime Value estimates the economic contribution of a
customer over the relationship.

A simplified model is:

    Expected lifetime
    =
    1 / (1 - retention rate)

Then:

    LTV
    =
    Revenue per period
    ×
    Gross margin
    ×
    Expected lifetime

This is only a simplified model.

A more rigorous model may include:

- Discount rate
- Churn probability
- Expansion revenue
- Cross-selling
- Support costs
- Payment costs
- Variable service costs
- Cohort behavior
- Different retention curves
""")


