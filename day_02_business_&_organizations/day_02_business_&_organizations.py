print("=" * 80)

def unit_economics(
    price,
    variable_cost,
    cac,
    monthly_churn,
    gross_margin=None
):
    contribution = price - variable_cost

    if gross_margin is None:
        gross_margin = contribution / price if price else 0

    if monthly_churn <= 0:
        lifetime = float("inf")
    else:
        lifetime = 1 / monthly_churn

    ltv = price * gross_margin * lifetime

    return {
        "price": price,
        "variable_cost": variable_cost,
        "contribution_margin": contribution,
        "gross_margin": gross_margin,
        "monthly_churn": monthly_churn,
        "expected_months": lifetime,
        "ltv": ltv,
        "cac": cac,
        "ltv_cac": ltv / cac if cac else float("inf")
    }


unit = unit_economics(
    price=100,
    variable_cost=20,
    cac=250,
    monthly_churn=0.05
)

for key, value in unit.items():
    if isinstance(value, float):
        print(f"{key:25s}: {value:.2f}")
    else:
        print(f"{key:25s}: {value}")

print("""
A complete unit-economic view connects:

    Price
    Variable cost
    Contribution margin
    Gross margin
    Churn
    Expected lifetime
    LTV
    CAC

This is more informative than looking at revenue alone.
""")


