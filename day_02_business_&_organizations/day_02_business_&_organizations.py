def contribution_margin(price, variable_cost):
    return price - variable_cost


def contribution_margin_ratio(price, variable_cost):
    return (price - variable_cost) / price


price = 100
variable_cost = 40

cm = contribution_margin(price, variable_cost)
cm_ratio = contribution_margin_ratio(price, variable_cost)

print(f"Price: ${price}")
print(f"Variable cost: ${variable_cost}")
print(f"Contribution margin: ${cm}")
print(f"Contribution margin ratio: {cm_ratio:.2%}")

print("""
Contribution margin shows how much revenue remains after variable
costs to contribute toward fixed costs and profit.

Formula:

    Contribution Margin
    =
    Revenue - Variable Costs

Contribution margin ratio:

    Contribution Margin Ratio
    =
    Contribution Margin / Revenue

If a product sells for $100 and variable cost is $40:

    Contribution margin = $60

Every additional unit contributes approximately $60 toward fixed costs
and profit, assuming the simplified cost structure remains valid.
""")


