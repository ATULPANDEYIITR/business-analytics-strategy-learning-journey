def break_even_units(fixed_costs, price, variable_cost):
    margin = price - variable_cost
    if margin <= 0:
        return None
    return fixed_costs / margin


fixed_costs = 120000
price = 100
variable_cost = 40

be_units = break_even_units(fixed_costs, price, variable_cost)

print(f"Fixed costs: ${fixed_costs:,.2f}")
print(f"Price per unit: ${price:,.2f}")
print(f"Variable cost per unit: ${variable_cost:,.2f}")
print(f"Break-even units: {be_units:,.0f}")

print("""
Break-even occurs when:

    Total Revenue = Total Costs

For a single product:

    Break-even units
    =
    Fixed Costs
    /
    (Price - Variable Cost)

The denominator is the contribution margin per unit.

If:

    Fixed costs = $120,000
    Price       = $100
    Variable    = $40

Then:

    Contribution margin = $60

    Break-even units
    = 120,000 / 60
    = 2,000 units

The business must sell 2,000 units to cover the simplified cost
structure.
""")


