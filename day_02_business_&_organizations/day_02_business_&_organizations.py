def roi(gain, investment):
    if investment == 0:
        return float("inf")
    return (gain - investment) / investment


investment = 100000
return_value = 130000

investment_return = roi(return_value, investment)

print(f"Initial investment: ${investment:,.2f}")
print(f"Final value: ${return_value:,.2f}")
print(f"ROI: {investment_return:.2%}")

print("""
ROI compares economic return with investment.

Simplified:

    ROI
    =
    (Return - Investment)
    /
    Investment

ROI is useful for comparing projects, but it ignores some important
factors such as:

- Timing
- Risk
- Cash-flow pattern
- Opportunity cost
- Strategic importance
- Terminal value

A project with a 20% return over one month is economically different
from a project with a 20% return over ten years.
""")


