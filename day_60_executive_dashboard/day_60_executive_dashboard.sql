CREATE INDEX IF NOT EXISTS ix_target_region_month
    ON fact_monthly_target (region_id, month_start);

CREATE INDEX IF NOT EXISTS ix_target_unit_month
    ON fact_monthly_target (business_unit_id, month_start);

COMMENT ON TABLE fact_monthly_actual IS
    'Monthly actual business performance at month, unit, and region grain.';

COMMENT ON TABLE fact_monthly_target IS
    'Monthly management targets at the same grain as actual performance.';

COMMENT ON COLUMN fact_monthly_actual.csat_score_sum IS
    'Sum of individual customer satisfaction scores on a 1-to-5 scale.';

COMMENT ON COLUMN fact_monthly_actual.revenue_cents IS
    'Revenue stored as integer cents to preserve financial precision.';


