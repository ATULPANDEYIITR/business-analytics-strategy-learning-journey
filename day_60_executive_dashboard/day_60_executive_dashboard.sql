    ROUND(
        100.0 * SUM(revenue_cents)
        / NULLIF(SUM(revenue_target_cents), 0),
        2
    ) AS revenue_attainment_pct,

    SUM(gross_profit_cents) AS gross_profit_cents,

    ROUND(
        100.0 * SUM(gross_profit_cents)
        / NULLIF(SUM(revenue_cents), 0),
        2
    ) AS gross_margin_pct,

    SUM(operating_profit_cents) AS operating_profit_cents,

    ROUND(
        100.0 * SUM(operating_profit_cents)
        / NULLIF(SUM(revenue_cents), 0),
        2
    ) AS operating_margin_pct,

    SUM(order_count) AS orders,
    SUM(delivered_orders) AS delivered_orders,

    ROUND(
        100.0 * SUM(delivered_orders)
        / NULLIF(SUM(order_count), 0),
        2
    ) AS fulfillment_pct,

    SUM(on_time_orders) AS on_time_orders,

    ROUND(
        100.0 * SUM(on_time_orders)
        / NULLIF(SUM(delivered_orders), 0),
        2
    ) AS on_time_delivery_pct,

    SUM(csat_score_sum) AS csat_score_sum,
    SUM(csat_responses) AS csat_responses,

    ROUND(
        SUM(csat_score_sum)
        / NULLIF(SUM(csat_responses), 0),
        2
    ) AS average_csat

FROM v_kpi_detail
GROUP BY
    business_unit_id,
    business_unit_name,
    region_id,
    region_name;


-- Parameterized reporting function for filtered dashboard queries.
CREATE OR REPLACE FUNCTION fn_dashboard_summary(
    p_from_month DATE,
    p_to_month DATE,
    p_region_id INTEGER DEFAULT NULL,
    p_business_unit_id INTEGER DEFAULT NULL
)
RETURNS TABLE (
    record_count BIGINT,
    revenue_cents NUMERIC,
    revenue_target_cents NUMERIC,
    revenue_attainment_pct NUMERIC,
    gross_profit_cents NUMERIC,
    gross_margin_pct NUMERIC,
    operating_profit_cents NUMERIC,
    operating_margin_pct NUMERIC,
    orders NUMERIC,
    delivered_orders NUMERIC,
    fulfillment_pct NUMERIC,
    on_time_orders NUMERIC,
    on_time_delivery_pct NUMERIC,
    csat_responses NUMERIC,
    average_csat NUMERIC
)
LANGUAGE plpgsql
STABLE
AS $function$
BEGIN
    IF p_from_month IS NULL OR p_to_month IS NULL THEN
        RAISE EXCEPTION 'Reporting period boundaries are required';
    END IF;

    IF p_from_month > p_to_month THEN
        RAISE EXCEPTION 'Start month cannot be later than end month';
    END IF;

    IF EXTRACT(DAY FROM p_from_month) <> 1
       OR EXTRACT(DAY FROM p_to_month) <> 1 THEN
        RAISE EXCEPTION 'Reporting dates must be first days of months';
    END IF;

    RETURN QUERY
    SELECT
        COUNT(*)::BIGINT,

        COALESCE(SUM(d.revenue_cents), 0)::NUMERIC,
        COALESCE(SUM(d.revenue_target_cents), 0)::NUMERIC,

        ROUND(
            100.0 * SUM(d.revenue_cents)
            / NULLIF(SUM(d.revenue_target_cents), 0),
            2
        ),

        COALESCE(SUM(d.gross_profit_cents), 0)::NUMERIC,

        ROUND(
            100.0 * SUM(d.gross_profit_cents)
            / NULLIF(SUM(d.revenue_cents), 0),
            2
        ),

        COALESCE(SUM(d.operating_profit_cents), 0)::NUMERIC,

        ROUND(
            100.0 * SUM(d.operating_profit_cents)
            / NULLIF(SUM(d.revenue_cents), 0),
            2
        ),

        COALESCE(SUM(d.order_count), 0)::NUMERIC,
        COALESCE(SUM(d.delivered_orders), 0)::NUMERIC,

        ROUND(
            100.0 * SUM(d.delivered_orders)
            / NULLIF(SUM(d.order_count), 0),
            2
        ),

        COALESCE(SUM(d.on_time_orders), 0)::NUMERIC,

        ROUND(
            100.0 * SUM(d.on_time_orders)
            / NULLIF(SUM(d.delivered_orders), 0),
            2
        ),

        COALESCE(SUM(d.csat_responses), 0)::NUMERIC,

        ROUND(
            SUM(d.csat_score_sum)
            / NULLIF(SUM(d.csat_responses), 0),
            2
        )

    FROM v_kpi_detail d
    WHERE d.month_start BETWEEN p_from_month AND p_to_month
      AND (
          p_region_id IS NULL
          OR d.region_id = p_region_id
      )
      AND (
          p_business_unit_id IS NULL
          OR d.business_unit_id = p_business_unit_id
      );
END;
$function$;


