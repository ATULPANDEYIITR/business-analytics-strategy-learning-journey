/*
 * Executive performance dashboard relational model.
 *
 * Target platform: PostgreSQL 15 or later.
 * Monetary values are stored in integer cents.
 *
 * The model uses shared dimensions and separate actual and target facts.
 * The monthly grain is one row per month, business unit, and region.
 *
 * The script is designed to be repeatable. Sample records are upserted.
 */

BEGIN;

CREATE SCHEMA IF NOT EXISTS exec_dashboard;
SET search_path TO exec_dashboard, public;

-- Calendar dimension used by both actual and target facts.
CREATE TABLE IF NOT EXISTS dim_month (
    month_start DATE PRIMARY KEY,
    year_num SMALLINT NOT NULL,
    month_num SMALLINT NOT NULL,
    quarter_num SMALLINT NOT NULL,
    month_label VARCHAR(20) NOT NULL,

    CONSTRAINT ck_month_first_day
        CHECK (EXTRACT(DAY FROM month_start) = 1),

    CONSTRAINT ck_month_number
        CHECK (month_num BETWEEN 1 AND 12),

    CONSTRAINT ck_quarter_number
        CHECK (quarter_num BETWEEN 1 AND 4),

    CONSTRAINT ck_month_year_consistency
        CHECK (
            year_num = EXTRACT(YEAR FROM month_start)::SMALLINT
            AND month_num = EXTRACT(MONTH FROM month_start)::SMALLINT
            AND quarter_num = ((month_num - 1) / 3) + 1
        ),

    CONSTRAINT uq_month_label UNIQUE (month_label)
);

CREATE TABLE IF NOT EXISTS dim_business_unit (
    business_unit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_code VARCHAR(30) NOT NULL UNIQUE,
    business_unit_name VARCHAR(100) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS dim_region (
    region_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_code VARCHAR(30) NOT NULL UNIQUE,
    region_name VARCHAR(100) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- Targets are kept separate from actual performance.
-- This prevents target values from being accidentally summed with actuals.
CREATE TABLE IF NOT EXISTS fact_monthly_target (
    month_start DATE NOT NULL,
    business_unit_id INTEGER NOT NULL,
    region_id INTEGER NOT NULL,

    revenue_target_cents BIGINT NOT NULL,
    gross_margin_target_pct NUMERIC(5, 2) NOT NULL,
    on_time_target_pct NUMERIC(5, 2) NOT NULL,
    csat_target NUMERIC(3, 2) NOT NULL,

    CONSTRAINT pk_fact_monthly_target
        PRIMARY KEY (month_start, business_unit_id, region_id),

    CONSTRAINT fk_target_month
        FOREIGN KEY (month_start)
        REFERENCES dim_month (month_start),

    CONSTRAINT fk_target_business_unit
        FOREIGN KEY (business_unit_id)
        REFERENCES dim_business_unit (business_unit_id),

    CONSTRAINT fk_target_region
        FOREIGN KEY (region_id)
        REFERENCES dim_region (region_id),

    CONSTRAINT ck_target_revenue
        CHECK (revenue_target_cents > 0),

    CONSTRAINT ck_target_gross_margin
        CHECK (gross_margin_target_pct BETWEEN 0 AND 100),

    CONSTRAINT ck_target_delivery
        CHECK (on_time_target_pct BETWEEN 0 AND 100),

    CONSTRAINT ck_target_csat
        CHECK (csat_target BETWEEN 1 AND 5)
);

-- Actual results reference their matching target row.
-- Deferred checking allows the two facts to be loaded in one transaction.
CREATE TABLE IF NOT EXISTS fact_monthly_actual (
    month_start DATE NOT NULL,
    business_unit_id INTEGER NOT NULL,
    region_id INTEGER NOT NULL,

    revenue_cents BIGINT NOT NULL,
    cogs_cents BIGINT NOT NULL,
    operating_expense_cents BIGINT NOT NULL,

    order_count BIGINT NOT NULL,
    delivered_orders BIGINT NOT NULL,
    on_time_orders BIGINT NOT NULL,

    csat_score_sum NUMERIC(14, 2) NOT NULL,
    csat_responses BIGINT NOT NULL,

    CONSTRAINT pk_fact_monthly_actual
        PRIMARY KEY (month_start, business_unit_id, region_id),

    CONSTRAINT fk_actual_month
        FOREIGN KEY (month_start)
        REFERENCES dim_month (month_start),

    CONSTRAINT fk_actual_business_unit
        FOREIGN KEY (business_unit_id)
        REFERENCES dim_business_unit (business_unit_id),

    CONSTRAINT fk_actual_region
        FOREIGN KEY (region_id)
        REFERENCES dim_region (region_id),

    CONSTRAINT fk_actual_target
        FOREIGN KEY (month_start, business_unit_id, region_id)
        REFERENCES fact_monthly_target (
            month_start,
            business_unit_id,
            region_id
        )
        DEFERRABLE INITIALLY DEFERRED,

    CONSTRAINT ck_actual_revenue
        CHECK (revenue_cents >= 0),

    CONSTRAINT ck_actual_cogs
        CHECK (cogs_cents >= 0),

    CONSTRAINT ck_actual_operating_expense
        CHECK (operating_expense_cents >= 0),

    CONSTRAINT ck_actual_order_counts
        CHECK (
            order_count >= 0
            AND delivered_orders >= 0
            AND on_time_orders >= 0
            AND delivered_orders <= order_count
            AND on_time_orders <= delivered_orders
        ),

    CONSTRAINT ck_actual_survey_counts
        CHECK (csat_responses >= 0),

    CONSTRAINT ck_actual_csat_scale
        CHECK (
            csat_score_sum >= 0
            AND (
                (csat_responses = 0 AND csat_score_sum = 0)
                OR (
                    csat_responses > 0
                    AND csat_score_sum >= csat_responses
                    AND csat_score_sum <= csat_responses * 5
                )
            )
        )
);

-- The primary keys already support the monthly composite joins.
-- These indexes support common region and business-unit filter paths.
CREATE INDEX IF NOT EXISTS ix_actual_region_month
    ON fact_monthly_actual (region_id, month_start);

CREATE INDEX IF NOT EXISTS ix_actual_unit_month
