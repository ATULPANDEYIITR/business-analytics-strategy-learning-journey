-- Security-invoker views preserve the querying user's table permissions
-- and row-level security policies.
CREATE OR REPLACE VIEW v_kpi_detail
WITH (security_invoker = TRUE)
AS
SELECT
    a.month_start,
    m.year_num,
    m.quarter_num,
    m.month_label,

    bu.business_unit_id,
    bu.business_unit_name,

    r.region_id,
    r.region_name,

    a.revenue_cents,
    t.revenue_target_cents,
    a.cogs_cents,
    a.operating_expense_cents,

    (a.revenue_cents - a.cogs_cents) AS gross_profit_cents,

    (
        a.revenue_cents
        - a.cogs_cents
        - a.operating_expense_cents
    ) AS operating_profit_cents,

    a.order_count,
    a.delivered_orders,
    a.on_time_orders,

    a.csat_score_sum,
    a.csat_responses,

    t.gross_margin_target_pct,
    t.on_time_target_pct,
    t.csat_target,

    ROUND(
        100.0 * a.revenue_cents
        / NULLIF(t.revenue_target_cents, 0),
        2
    ) AS revenue_attainment_pct,

    ROUND(
        100.0 * (a.revenue_cents - a.cogs_cents)
        / NULLIF(a.revenue_cents, 0),
        2
    ) AS gross_margin_pct,

    ROUND(
        100.0 * (
            a.revenue_cents
            - a.cogs_cents
            - a.operating_expense_cents
        ) / NULLIF(a.revenue_cents, 0),
        2
    ) AS operating_margin_pct,

    ROUND(
        100.0 * a.delivered_orders
        / NULLIF(a.order_count, 0),
        2
    ) AS fulfillment_pct,

    ROUND(
        100.0 * a.on_time_orders
        / NULLIF(a.delivered_orders, 0),
        2
    ) AS on_time_delivery_pct,

    ROUND(
        a.csat_score_sum
        / NULLIF(a.csat_responses, 0),
        2
    ) AS average_csat,

    CASE
        WHEN a.revenue_cents::NUMERIC
             / NULLIF(t.revenue_target_cents, 0) < 0.95
            THEN 'CRITICAL'
        WHEN a.revenue_cents < t.revenue_target_cents
            THEN 'WARNING'
        ELSE 'ON_TRACK'
    END AS revenue_status,

    CASE
        WHEN a.delivered_orders = 0 THEN 'NO_DATA'
        WHEN 100.0 * a.on_time_orders
             / NULLIF(a.delivered_orders, 0) < t.on_time_target_pct
            THEN 'BELOW_TARGET'
        ELSE 'ON_TRACK'
    END AS delivery_status

FROM fact_monthly_actual a
JOIN fact_monthly_target t
    ON t.month_start = a.month_start
    AND t.business_unit_id = a.business_unit_id
    AND t.region_id = a.region_id
JOIN dim_month m
    ON m.month_start = a.month_start
JOIN dim_business_unit bu
    ON bu.business_unit_id = a.business_unit_id
JOIN dim_region r
    ON r.region_id = a.region_id;


-- Management-level monthly roll-up.
-- Ratios are recalculated from additive totals, not averaged from segments.
CREATE OR REPLACE VIEW v_executive_monthly
WITH (security_invoker = TRUE)
AS
SELECT
    month_start,
    year_num,
    quarter_num,
    month_label,

    COUNT(*) AS reporting_segments,

    SUM(revenue_cents) AS revenue_cents,
    SUM(revenue_target_cents) AS revenue_target_cents,

    ROUND(
        100.0 * SUM(revenue_cents)
        / NULLIF(SUM(revenue_target_cents), 0),
        2
    ) AS revenue_attainment_pct,

    SUM(gross_profit_cents) AS gross_profit_cents,

    ROUND(
        100.0 * SUM(gross_profit_cents)
        / NULLIF(SUM(revenue_cents), 0),
        2
    ) AS gross_margin_pct,

    SUM(operating_profit_cents) AS operating_profit_cents,

    ROUND(
        100.0 * SUM(operating_profit_cents)
        / NULLIF(SUM(revenue_cents), 0),
        2
    ) AS operating_margin_pct,

    SUM(order_count) AS orders,
    SUM(delivered_orders) AS delivered_orders,

    ROUND(
        100.0 * SUM(delivered_orders)
        / NULLIF(SUM(order_count), 0),
        2
    ) AS fulfillment_pct,

    SUM(on_time_orders) AS on_time_orders,

    ROUND(
        100.0 * SUM(on_time_orders)
        / NULLIF(SUM(delivered_orders), 0),
        2
    ) AS on_time_delivery_pct,

    SUM(csat_score_sum) AS csat_score_sum,
    SUM(csat_responses) AS csat_responses,

    ROUND(
        SUM(csat_score_sum)
        / NULLIF(SUM(csat_responses), 0),
        2
    ) AS average_csat

FROM v_kpi_detail
GROUP BY
    month_start,
    year_num,
    quarter_num,
    month_label;


-- Business-unit and regional performance for drill-down reporting.
