-- Rank business-unit and region combinations by revenue attainment.
SELECT
    business_unit_name,
    region_name,
    revenue_attainment_pct,
    DENSE_RANK() OVER (
        ORDER BY revenue_attainment_pct DESC NULLS LAST
    ) AS attainment_rank
FROM v_segment_performance
ORDER BY attainment_rank;


-- Data-quality check: every actual row must have a matching target.
-- The expected result is zero rows.
SELECT
    a.month_start,
    a.business_unit_id,
    a.region_id
FROM fact_monthly_actual a
LEFT JOIN fact_monthly_target t
    ON t.month_start = a.month_start
    AND t.business_unit_id = a.business_unit_id
    AND t.region_id = a.region_id
WHERE t.month_start IS NULL;


-- Threshold report for revenue and delivery performance.
SELECT
    month_label,
    business_unit_name,
    region_name,
    revenue_status,
    delivery_status,
    revenue_attainment_pct,
    on_time_delivery_pct
FROM v_kpi_detail
WHERE revenue_status <> 'ON_TRACK'
   OR delivery_status <> 'ON_TRACK'
ORDER BY month_start, business_unit_name, region_name;
